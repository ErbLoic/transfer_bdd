// Colonnes brutes d'un moteur → colonnes canoniques (type, défaut, auto-incrément).
function canonicalColumns(rows, dialect) {
  return rows.map((row) => {
    const parsedDefault = row.identity ? null : parseDefault(row.defaultValue, { literal: row.literalDefault })
    return {
      name: row.name,
      raw: String(row.rawType || ''),
      nullable: Boolean(row.nullable),
      primary: Boolean(row.primary),
      identity: Boolean(row.identity) || parsedDefault?.kind === 'identity',
      default: parsedDefault?.kind === 'identity' ? null : parsedDefault,
      ...toCanonicalType({ rawType: row.rawType, length: row.length, precision: row.precision, scale: row.scale, dialect }),
    }
  })
}

// Regroupe des lignes « une par colonne » en index complets.
function groupIndexes(rows) {
  const byName = new Map()
  for (const row of rows) {
    const key = String(row.name)
    if (!byName.has(key)) byName.set(key, { name: row.name, unique: Boolean(row.unique), columns: [], complex: false })
    const index = byName.get(key)
    if (row.complex || !row.col) index.complex = true
    else index.columns.push(row.col)
  }
  return [...byName.values()]
}

// CREATE TABLE générique : types, clé primaire, défauts, auto-incrément
// (et clés étrangères en ligne pour SQLite, qui ne sait pas les ajouter après coup).
// `adapter` n'a besoin que de kind, quote et table : il peut être virtuel (export SQL).
export function buildCreateTable(adapter, table, columns, foreignKeys = []) {
  const warnings = []
  const primary = columns.filter((column) => column.primary)
  const identityColumn = columns.find((column) => column.identity)
  let identity = null
  const definitions = columns.map((column) => {
    // Une clé primaire ne peut pas être un texte illimité sur la plupart des moteurs.
    let effective = column.primary && column.type === 'text' ? { ...column, type: 'varchar', length: 255 } : column
    let typeSql
    let extra = ''
    if (column === identityColumn) {
      effective = { ...effective, type: ['smallint', 'integer', 'bigint'].includes(effective.type) ? effective.type : 'bigint' }
      typeSql = canonicalToSql(effective, adapter.kind)
      if (['postgres', 'oracle'].includes(adapter.kind)) extra = ' GENERATED BY DEFAULT AS IDENTITY'
      else if (adapter.kind === 'mssql') extra = ' IDENTITY(1,1)'
      else if (adapter.kind === 'mysql' && column.primary && primary[0] === column) extra = ' AUTO_INCREMENT'
      else if (adapter.kind === 'sqlite' && column.primary && primary.length === 1) typeSql = 'INTEGER'
      else warnings.push(`${table}.${column.name} : auto-incrément non recréé (la colonne doit être la clé primaire).`)
      if (extra || typeSql === 'INTEGER') identity = column.name
    } else {
      typeSql = canonicalToSql(effective, adapter.kind)
      if (column.default?.kind === 'unsupported') warnings.push(`${table}.${column.name} : valeur par défaut « ${column.default.raw} » non convertible, ignorée.`)
      else if (column.default) {
        const rendered = renderDefault(column.default, effective, adapter.kind)
        if (rendered) extra = ` DEFAULT ${rendered}`
        else warnings.push(`${table}.${column.name} : valeur par défaut non compatible avec ${adapter.kind}, ignorée.`)
      }
    }
    return `${adapter.quote(column.name)} ${typeSql}${extra}${column.nullable && !column.primary ? '' : ' NOT NULL'}`
  })
  if (primary.length) definitions.push(`PRIMARY KEY (${primary.map((column) => adapter.quote(column.name)).join(', ')})`)
  for (const fk of foreignKeys) definitions.push(foreignKeySql(adapter, table, fk))
  return { sql: `CREATE TABLE ${adapter.table(table)} (${definitions.join(', ')})`, warnings, identity }
}

export function foreignKeySql(adapter, table, fk) {
  const q = adapter.quote
  const actions = renderForeignKeyActions(fk, adapter.kind)
  return `CONSTRAINT ${q(foreignKeyName(table, fk))} FOREIGN KEY (${fk.columns.map(q).join(', ')}) REFERENCES ${adapter.table(fk.refTable)} (${fk.refColumns.map(q).join(', ')})${actions ? ` ${actions}` : ''}`
}

// Nom d'index unique dans la cible (PostgreSQL, Oracle et SQLite exigent l'unicité dans tout le schéma).
export function indexName(table, index) {
  const name = String(index.name)
  return (name.toLowerCase().startsWith(table.toLowerCase()) ? name : `${table}_${name}`).slice(0, 60)
}

export function indexSql(adapter, table, index) {
  return `CREATE ${index.unique ? 'UNIQUE ' : ''}INDEX ${adapter.quote(indexName(table, index))} ON ${adapter.table(table)} (${index.columns.map(adapter.quote).join(', ')})`
}

// Pourquoi une colonne ne peut pas être indexée dans le moteur cible (null si elle peut l'être).
export function indexBlocker(column, kind) {
  if (!column) return 'colonne absente'
  const unbounded = ['text', 'json', 'binary'].includes(column.type)
  if (kind === 'mysql' && (unbounded || (column.type === 'varchar' && column.length > 768))) return `${column.name} est un texte trop long pour un index MySQL`
  if (kind === 'mssql' && (unbounded || (column.type === 'varchar' && column.length > 850))) return `${column.name} est trop long pour un index SQL Server`
  if (kind === 'oracle' && (unbounded || (column.type === 'varchar' && column.length > 4000))) return `${column.name} est un CLOB/BLOB, non indexable par Oracle`
  return null
}

// Insertion multi-lignes avec placeholders, découpée selon la limite de paramètres du moteur.
async function insertWithPlaceholders(adapter, table, columns, rows, { maxParams, maxRows = Infinity, placeholder, types, wrap = (sql) => sql }) {
  const rowsPerBatch = Math.max(1, Math.min(maxRows, Math.floor(maxParams / columns.length)))
  const columnSql = columns.map((column) => adapter.quote(column.name)).join(', ')
  for (const batch of chunk(rows, rowsPerBatch)) {
    const values = []
    const valueTypes = []
    const tuples = batch.map((row) => `(${columns.map((column) => {
      values.push(prepareValue(row[column.name], column, adapter.kind))
      valueTypes.push(types?.(column))
      return placeholder(values.length - 1)
    }).join(', ')})`)
    await adapter.query(wrap(`INSERT INTO ${adapter.table(table)} (${columnSql}) VALUES ${tuples.join(', ')}`), values, valueTypes)
  }
}

const limitOffset = (order, limit, offset) => `${order} LIMIT ${limit} OFFSET ${offset}`
const offsetFetch = (order, limit, offset) => `${order} OFFSET ${offset} ROWS FETCH NEXT ${limit} ROWS ONLY`

async function connectMysql(url) {
  const client = await mysql.createConnection({
    host: url.hostname, port: Number(url.port || 3306), user: decode(url.username), password: decode(url.password),
    database: decode(url.pathname.slice(1)), connectTimeout: 8000,
    // Précision maximale : grands entiers, décimaux et dates restent du texte exact.
    supportBigNumbers: true, bigNumberStrings: true, dateStrings: true, timezone: 'Z',
    typeCast: (field, next) => field.type === 'JSON' ? field.string('utf8') : next(),
  })
  // Permet de recréer des tables liées par des clés étrangères dans n'importe quel ordre.
  await client.query('SET FOREIGN_KEY_CHECKS = 0')
  await client.query("SET time_zone = '+00:00'")
  const [[{ version }]] = await client.query('SELECT VERSION() AS version')
  // MariaDB renvoie les défauts sous forme d'expressions, MySQL 8 sous forme de constantes brutes.
  const isMariaDb = /mariadb/i.test(version)
  const q = quoteWith('`')
  const adapter = {
    kind: 'mysql',
    transactional: false,
    quote: q,
    table: q,
    ph: () => '?',
    page: limitOffset,
    selectList: (columns) => columns.map((column) => q(column.name)).join(', '),
    query: async (sql, params = []) => (await client.query(sql, params))[0],
    listTables: async () => (await adapter.query("SHOW FULL TABLES WHERE Table_type = 'BASE TABLE'")).map((row) => Object.values(row)[0]),
    getColumns: async (table) => canonicalColumns((await adapter.query(
      `SELECT COLUMN_NAME name, COLUMN_TYPE rawType, CHARACTER_MAXIMUM_LENGTH length, NUMERIC_PRECISION \`precision\`, NUMERIC_SCALE scale,
              IS_NULLABLE = 'YES' nullable, COLUMN_KEY = 'PRI' \`primary\`, COLUMN_DEFAULT defaultValue, EXTRA extra
       FROM information_schema.columns WHERE table_schema = DATABASE() AND table_name = ? ORDER BY ORDINAL_POSITION`, [table],
    )).map((row) => ({
      ...row, identity: /auto_increment/i.test(row.extra),
      literalDefault: !isMariaDb && !/DEFAULT_GENERATED/i.test(row.extra),
    })), 'mysql'),
    getForeignKeys: async (table) => groupForeignKeys(await adapter.query(
      `SELECT k.CONSTRAINT_NAME name, k.COLUMN_NAME col, k.REFERENCED_TABLE_NAME refTable, k.REFERENCED_COLUMN_NAME refCol,
              r.DELETE_RULE onDelete, r.UPDATE_RULE onUpdate
       FROM information_schema.KEY_COLUMN_USAGE k
       JOIN information_schema.REFERENTIAL_CONSTRAINTS r ON r.CONSTRAINT_SCHEMA = k.CONSTRAINT_SCHEMA AND r.CONSTRAINT_NAME = k.CONSTRAINT_NAME AND r.TABLE_NAME = k.TABLE_NAME
       WHERE k.TABLE_SCHEMA = DATABASE() AND k.TABLE_NAME = ? AND k.REFERENCED_TABLE_NAME IS NOT NULL
       ORDER BY k.CONSTRAINT_NAME, k.ORDINAL_POSITION`, [table],
    )),
    getIndexes: async (table) => groupIndexes((await adapter.query(
      `SELECT INDEX_NAME name, NON_UNIQUE = 0 \`unique\`, COLUMN_NAME col, SUB_PART sub, INDEX_TYPE itype
       FROM information_schema.STATISTICS WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = ? AND INDEX_NAME <> 'PRIMARY'
       ORDER BY INDEX_NAME, SEQ_IN_INDEX`, [table],
    )).map((row) => ({ ...row, complex: row.sub != null || !['BTREE', 'HASH'].includes(row.itype) }))),
    // Entre deux MySQL, on reprend la définition native complète (index, clés étrangères, défauts…).
    nativeCreate: async (table) => Object.values((await adapter.query(`SHOW CREATE TABLE ${q(table)}`))[0])[1],
    dropTable: (table) => adapter.query(`DROP TABLE IF EXISTS ${q(table)}`),
    insertRows: (table, columns, rows) => insertWithPlaceholders(adapter, table, columns, rows, { maxParams: 60000, placeholder: () => '?' }),
    close: () => client.end(),
  }
  return adapter
}

async function connectPostgres(url) {
  const schema = url.searchParams.get('schema')
  const clean = new URL(url.toString())
  clean.searchParams.delete('schema')
  const client = new pg.Client({
    connectionString: clean.toString(), connectionTimeoutMillis: 8000,
    ssl: url.searchParams.get('sslmode') === 'require' ? { rejectUnauthorized: false } : false,
  })
  await client.connect()
  const q = quoteWith('"')
  // Le schéma choisi devient le schéma courant : les noms de tables non qualifiés y sont résolus.
  if (schema) await client.query(`SET search_path TO ${q(schema)}`)
  const adapter = {
    kind: 'postgres',
    transactional: true,
    quote: q,
    table: q,
    ph: (index) => `$${index + 1}`,
    page: limitOffset,
    selectList: (columns) => columns.map((column) => q(column.name)).join(', '),
    query: async (sql, params = []) => (await client.query(sql, params)).rows,
    listTables: async () => (await adapter.query(
      "SELECT table_name FROM information_schema.tables WHERE table_schema = current_schema() AND table_type = 'BASE TABLE' ORDER BY table_name",
    )).map((row) => row.table_name),
    getColumns: async (table) => canonicalColumns(await adapter.query(
      `SELECT c.column_name AS name,
              CASE WHEN c.data_type = 'USER-DEFINED' THEN c.udt_name ELSE c.data_type END AS "rawType",
              c.character_maximum_length AS length, c.numeric_precision AS precision, c.numeric_scale AS scale,
              c.is_nullable = 'YES' AS nullable, c.column_default AS "defaultValue", c.is_identity = 'YES' AS identity,
              EXISTS (SELECT 1 FROM information_schema.table_constraints tc
                      JOIN information_schema.key_column_usage k ON k.constraint_name = tc.constraint_name AND k.table_schema = tc.table_schema
                      WHERE tc.constraint_type = 'PRIMARY KEY' AND tc.table_schema = c.table_schema AND tc.table_name = c.table_name AND k.column_name = c.column_name) AS primary
       FROM information_schema.columns c WHERE c.table_schema = current_schema() AND c.table_name = $1 ORDER BY c.ordinal_position`, [table],
    ), 'postgres'),
    getForeignKeys: async (table) => (await adapter.query(
      `SELECT con.conname AS name,
              ARRAY(SELECT att.attname::text FROM unnest(con.conkey) WITH ORDINALITY k(attnum, ord)
                    JOIN pg_attribute att ON att.attrelid = con.conrelid AND att.attnum = k.attnum ORDER BY k.ord) AS columns,
              ref.relname AS "refTable",
              ARRAY(SELECT att.attname::text FROM unnest(con.confkey) WITH ORDINALITY k(attnum, ord)
                    JOIN pg_attribute att ON att.attrelid = con.confrelid AND att.attnum = k.attnum ORDER BY k.ord) AS "refColumns",
              con.confdeltype AS "onDelete", con.confupdtype AS "onUpdate"
       FROM pg_constraint con
       JOIN pg_class rel ON rel.oid = con.conrelid JOIN pg_namespace n ON n.oid = rel.relnamespace
       JOIN pg_class ref ON ref.oid = con.confrelid
       WHERE con.contype = 'f' AND n.nspname = current_schema() AND rel.relname = $1 ORDER BY con.conname`, [table],
    )).map((fk) => groupForeignKeys(fk.columns.map((col, index) => ({ ...fk, col, refCol: fk.refColumns[index] })))[0]),
    getIndexes: async (table) => (await adapter.query(
      `SELECT i.relname AS name, ix.indisunique AS unique,
              ARRAY(SELECT a.attname::text FROM unnest(ix.indkey::int2[]) WITH ORDINALITY k(attnum, ord)
                    JOIN pg_attribute a ON a.attrelid = ix.indrelid AND a.attnum = k.attnum
                    WHERE k.ord <= ix.indnkeyatts ORDER BY k.ord) AS columns,
              (ix.indexprs IS NOT NULL OR ix.indpred IS NOT NULL OR am.amname <> 'btree') AS complex
       FROM pg_index ix
       JOIN pg_class t ON t.oid = ix.indrelid JOIN pg_class i ON i.oid = ix.indexrelid
       JOIN pg_namespace ns ON ns.oid = t.relnamespace JOIN pg_am am ON am.oid = i.relam
       WHERE ns.nspname = current_schema() AND t.relname = $1 AND NOT ix.indisprimary ORDER BY i.relname`, [table],
    )).map((row) => ({ name: row.name, unique: row.unique, columns: row.columns, complex: row.complex || row.columns.length === 0 })),
    getChecks: async (table) => (await adapter.query(
      `SELECT con.conname AS name, pg_get_constraintdef(con.oid) AS clause FROM pg_constraint con
       JOIN pg_class rel ON rel.oid = con.conrelid JOIN pg_namespace n ON n.oid = rel.relnamespace
       WHERE con.contype = 'c' AND n.nspname = current_schema() AND rel.relname = $1 ORDER BY con.conname`, [table],
    )).map((row) => ({ name: row.name, clause: row.clause.replace(/\s+NOT VALID$/i, '') })),
    dropTable: (table) => adapter.query(`DROP TABLE IF EXISTS ${q(table)} CASCADE`),
    insertRows: (table, columns, rows) => insertWithPlaceholders(adapter, table, columns, rows, { maxParams: 65000, placeholder: (index) => `$${index + 1}` }),
    // Recale la séquence de l'auto-incrément après insertion d'identifiants explicites.
    syncIdentity: (table, column) => adapter.query(
      `SELECT setval(pg_get_serial_sequence($1, $2), MAX(${q(column)})) FROM ${q(table)} HAVING MAX(${q(column)}) IS NOT NULL`, [q(table), column],
    ),
    begin: () => adapter.query('BEGIN'),
    commit: () => adapter.query('COMMIT'),
    rollback: () => adapter.query('ROLLBACK'),
    close: () => client.end(),
  }
  return adapter
}

// SQL Server : lecture convertie en texte pour garder décimaux et fractions de seconde exacts.
function mssqlSelectExpression(column, q) {
  const base = column.raw.toLowerCase()
  const name = q(column.name)
  if (['decimal', 'numeric', 'money', 'smallmoney'].includes(base)) return `CAST(${name} AS VARCHAR(50)) AS ${name}`
  if (['datetime', 'datetime2', 'smalldatetime'].includes(base)) return `CONVERT(VARCHAR(27), ${name}, 121) AS ${name}`
  if (base === 'date') return `CONVERT(VARCHAR(10), ${name}, 23) AS ${name}`
  if (['time', 'datetimeoffset'].includes(base)) return `CAST(${name} AS VARCHAR(34)) AS ${name}`
  return name
}

async function connectMssql(url) {
  const flag = (name, fallback) => url.searchParams.has(name) ? url.searchParams.get(name) === 'true' : fallback
  // Une seule connexion : les transactions et IDENTITY_INSERT sont liés à la session.
  const pool = await new mssql.ConnectionPool({
    server: url.hostname, port: Number(url.port || 1433), user: decode(url.username), password: decode(url.password),
    database: decode(url.pathname.slice(1)) || undefined, connectionTimeout: 8000, requestTimeout: 300000,
    pool: { max: 1, min: 0 },
    options: { encrypt: flag('encrypt', true), trustServerCertificate: flag('trustServerCertificate', false) },
  }).connect()
  const q = quoteWith('[', ']')
  const schema = url.searchParams.get('schema') || (await pool.request().query('SELECT SCHEMA_NAME() AS s')).recordset[0].s
  // SQL Server n'a pas de schéma courant modifiable : les tables sont toujours qualifiées.
  const table = (name) => `${q(schema)}.${q(name)}`
  const schemaLiteral = `N${sqlString(schema)}`
  // Les transactions passent par l'API du pilote : un BEGIN brut serait exécuté via sp_executesql et refusé.
  let transaction = null
  const adapter = {
    kind: 'mssql',
    transactional: true,
    quote: q,
    table,
    ph: (index) => `@p${index}`,
    page: offsetFetch,
    selectList: (columns) => columns.map((column) => mssqlSelectExpression(column, q)).join(', '),
    query: async (sql, params = [], types = []) => {
      const request = transaction ? new mssql.Request(transaction) : pool.request()
      params.forEach((value, index) => types[index] ? request.input(`p${index}`, types[index], value) : request.input(`p${index}`, value))
      return (await request.query(sql)).recordset || []
    },
    listTables: async () => (await adapter.query(
      `SELECT TABLE_NAME name FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_TYPE = 'BASE TABLE' AND TABLE_SCHEMA = ${schemaLiteral} ORDER BY TABLE_NAME`,
    )).map((row) => row.name),
    getColumns: async (name) => canonicalColumns(await adapter.query(
      `SELECT c.COLUMN_NAME name, c.DATA_TYPE rawType, c.CHARACTER_MAXIMUM_LENGTH length, c.NUMERIC_PRECISION [precision], c.NUMERIC_SCALE scale,
              CAST(CASE WHEN c.IS_NULLABLE = 'YES' THEN 1 ELSE 0 END AS BIT) nullable, c.COLUMN_DEFAULT defaultValue,
              CAST(COLUMNPROPERTY(OBJECT_ID(QUOTENAME(c.TABLE_SCHEMA) + '.' + QUOTENAME(c.TABLE_NAME)), c.COLUMN_NAME, 'IsIdentity') AS BIT) [identity],
              CAST(CASE WHEN EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS tc
                                JOIN INFORMATION_SCHEMA.KEY_COLUMN_USAGE k ON k.CONSTRAINT_NAME = tc.CONSTRAINT_NAME AND k.TABLE_SCHEMA = tc.TABLE_SCHEMA
                                WHERE tc.CONSTRAINT_TYPE = 'PRIMARY KEY' AND tc.TABLE_SCHEMA = c.TABLE_SCHEMA AND tc.TABLE_NAME = c.TABLE_NAME AND k.COLUMN_NAME = c.COLUMN_NAME)
                   THEN 1 ELSE 0 END AS BIT) [primary]
       FROM INFORMATION_SCHEMA.COLUMNS c WHERE c.TABLE_SCHEMA = ${schemaLiteral} AND c.TABLE_NAME = @p0 ORDER BY c.ORDINAL_POSITION`, [name],
    ), 'mssql'),
    getForeignKeys: async (name) => groupForeignKeys(await adapter.query(
      `SELECT fk.name, pc.name col, OBJECT_NAME(fk.referenced_object_id) refTable, rc.name refCol,
              fk.delete_referential_action_desc onDelete, fk.update_referential_action_desc onUpdate
       FROM sys.foreign_keys fk
       JOIN sys.foreign_key_columns fkc ON fkc.constraint_object_id = fk.object_id
       JOIN sys.columns pc ON pc.object_id = fkc.parent_object_id AND pc.column_id = fkc.parent_column_id
       JOIN sys.columns rc ON rc.object_id = fkc.referenced_object_id AND rc.column_id = fkc.referenced_column_id
       WHERE fk.parent_object_id = OBJECT_ID(@p0)
       ORDER BY fk.name, fkc.constraint_column_id`, [table(name)],
    )),
    getIndexes: async (name) => groupIndexes((await adapter.query(
      `SELECT i.name, i.is_unique [unique], c.name col, i.has_filter complex
       FROM sys.indexes i
       JOIN sys.index_columns ic ON ic.object_id = i.object_id AND ic.index_id = i.index_id AND ic.is_included_column = 0
       JOIN sys.columns c ON c.object_id = ic.object_id AND c.column_id = ic.column_id
       WHERE i.object_id = OBJECT_ID(@p0) AND i.is_primary_key = 0 AND i.type IN (1, 2)
       ORDER BY i.name, ic.key_ordinal`, [table(name)],
    ))),
    getChecks: async (name) => (await adapter.query(
      'SELECT name, definition FROM sys.check_constraints WHERE parent_object_id = OBJECT_ID(@p0) ORDER BY name', [table(name)],
    )).map((row) => ({ name: row.name, clause: `CHECK ${row.definition}` })),
    // SQL Server refuse de supprimer une table encore référencée : on retire d'abord ces clés étrangères.
    dropTable: (name) => adapter.query(
      `DECLARE @sql NVARCHAR(MAX) = N'';
       SELECT @sql += N'ALTER TABLE ' + QUOTENAME(OBJECT_SCHEMA_NAME(parent_object_id)) + N'.' + QUOTENAME(OBJECT_NAME(parent_object_id)) + N' DROP CONSTRAINT ' + QUOTENAME(name) + N';'
       FROM sys.foreign_keys WHERE referenced_object_id = OBJECT_ID(@p0);
       EXEC sp_executesql @sql;
       DROP TABLE IF EXISTS ${table(name)};`, [table(name)],
    ),
    // 2100 paramètres et 1000 lignes maximum par requête.
    insertRows: (name, columns, rows, { identity } = {}) => insertWithPlaceholders(adapter, name, columns, rows, {
      maxParams: 2000, maxRows: 1000, placeholder: (index) => `@p${index}`,
      // Un NULL non typé est envoyé en NVARCHAR, refusé par une colonne binaire.
      types: (column) => column.type === 'binary' ? mssql.VarBinary(mssql.MAX) : undefined,
      // IDENTITY_INSERT doit être dans le même lot que l'INSERT (exécuté via sp_executesql).
      wrap: (sql) => identity ? `SET IDENTITY_INSERT ${table(name)} ON; ${sql}; SET IDENTITY_INSERT ${table(name)} OFF;` : sql,
    }),
    begin: async () => { transaction = new mssql.Transaction(pool); await transaction.begin() },
    commit: async () => { await transaction.commit(); transaction = null },
    rollback: async () => { if (transaction) { const current = transaction; transaction = null; await current.rollback() } },
    close: () => pool.close(),
  }
  return adapter
}

async function connectSqlite(connectionString) {
  const path = decode(connectionString.replace(/^sqlite3?:(\/\/)?/i, '').replace(/\?.*$/, ''))
  if (!path) throw new Error('Chemin du fichier SQLite manquant, par exemple sqlite:///data/ma_base.db')
  const db = new DatabaseSync(path)
  const q = quoteWith('"')
  const adapter = {
    kind: 'sqlite',
    transactional: true,
    quote: q,
    table: q,
    ph: () => '?',
    page: limitOffset,
    selectList: (columns) => columns.map((column) => q(column.name)).join(', '),
    query: async (sql, params = []) => {
      const statement = db.prepare(sql)
      return /^\s*(select|pragma|with)/i.test(sql) ? statement.all(...params) : (statement.run(...params), [])
    },
    // Lecture des données : entiers 64 bits en BigInt pour ne rien arrondir.
    read: async (sql, params = []) => {
      const statement = db.prepare(sql)
      statement.setReadBigInts(true)
      return statement.all(...params).map((row) => ({ ...row }))
    },
    count: async (table) => Number(db.prepare(`SELECT COUNT(*) AS n FROM ${q(table)}`).get().n),
    listTables: async () => (await adapter.query(
      "SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY name",
    )).map((row) => row.name),
    getColumns: async (table) => {
      const rows = await adapter.query(`PRAGMA table_info(${q(table)})`)
      const primaryCount = rows.filter((row) => row.pk > 0).length
      return canonicalColumns(rows.map((row) => ({
        name: row.name, rawType: row.type, nullable: !row.notnull, primary: row.pk > 0, defaultValue: row.dflt_value,
        // INTEGER PRIMARY KEY est un alias de rowid, donc auto-incrémenté.
        identity: row.pk > 0 && primaryCount === 1 && String(row.type).toUpperCase() === 'INTEGER',
      })), 'sqlite')
    },
    getForeignKeys: async (table) => {
      const rows = await adapter.query(`PRAGMA foreign_key_list(${q(table)})`)
      const resolved = []
      for (const row of rows) {
        let refCol = row.to
        // Sans colonne explicite, la référence vise la clé primaire de la table cible.
        if (!refCol) refCol = (await adapter.query(`PRAGMA table_info(${q(row.table)})`)).filter((info) => info.pk > 0).sort((a, b) => a.pk - b.pk)[row.seq]?.name
        resolved.push({ name: `fk_${table}_${row.id}`, col: row.from, refTable: row.table, refCol, onDelete: row.on_delete, onUpdate: row.on_update })
      }
      return groupForeignKeys(resolved)
    },
    getIndexes: async (table) => {
      const indexes = []
      for (const index of await adapter.query(`PRAGMA index_list(${q(table)})`)) {
        if (index.origin === 'pk') continue
        const columns = (await adapter.query(`PRAGMA index_info(${q(index.name)})`)).sort((a, b) => a.seqno - b.seqno)
        indexes.push({ name: index.name, unique: Boolean(index.unique), columns: columns.map((column) => column.name).filter(Boolean), complex: Boolean(index.partial) || columns.some((column) => !column.name) })
      }
      return indexes
    },
    dropTable: (table) => adapter.query(`DROP TABLE IF EXISTS ${q(table)}`),
    insertRows: (table, columns, rows) => insertWithPlaceholders(adapter, table, columns, rows, { maxParams: 32000, placeholder: () => '?' }),
    inlineForeignKeys: true,
    begin: async () => db.exec('BEGIN'),
    commit: async () => db.exec('COMMIT'),
    rollback: async () => { if (db.isTransaction) db.exec('ROLLBACK') },
    close: async () => db.close(),
  }
  return adapter
}

// Oracle : dates et horodatages lus en texte complet (jusqu'à la nanoseconde).
function oracleSelectExpression(column, q) {
  const raw = column.raw.toUpperCase()
  const name = q(column.name)
  if (raw === 'DATE') return `TO_CHAR(${name}, 'YYYY-MM-DD HH24:MI:SS') AS ${name}`
  if (raw.startsWith('TIMESTAMP') && raw.includes('WITH TIME ZONE') && !raw.includes('LOCAL')) return `TO_CHAR(${name}, 'YYYY-MM-DD HH24:MI:SS.FF9 TZH:TZM') AS ${name}`
  if (raw.startsWith('TIMESTAMP')) return `TO_CHAR(${name}, 'YYYY-MM-DD HH24:MI:SS.FF9') AS ${name}`
  return name
}

async function connectOracle(url) {
  const connection = await oracledb.getConnection({
    user: decode(url.username), password: decode(url.password),
    connectString: `${url.hostname}:${url.port || 1521}/${decode(url.pathname.slice(1))}`,
  })
  // Séparateur décimal fixe pour convertir les décimaux transmis en texte.
  await connection.execute("ALTER SESSION SET NLS_NUMERIC_CHARACTERS = '.,'")
  const q = quoteWith('"')
  const requested = url.searchParams.get('schema')
  // Le schéma choisi devient le schéma courant : les noms non qualifiés y sont résolus.
  if (requested) await connection.execute(`ALTER SESSION SET CURRENT_SCHEMA = ${q(requested.toUpperCase())}`)
  const owner = requested ? requested.toUpperCase() : (await connection.execute('SELECT USER AS "u" FROM dual')).rows[0].u
  const NUMBER_TYPES = ['boolean', 'smallint', 'integer', 'float', 'double']
  const bindDef = (column, rows) => {
    if (NUMBER_TYPES.includes(column.type)) return { type: oracledb.DB_TYPE_NUMBER }
    if (column.type === 'binary') return { type: oracledb.DB_TYPE_BLOB }
    if (column.type === 'text' || column.type === 'json' || (column.type === 'varchar' && column.length > 4000)) return { type: oracledb.DB_TYPE_CLOB }
    const maxSize = Math.max(1, ...rows.map((row) => row[column.name] == null ? 0 : Buffer.byteLength(String(prepareValue(row[column.name], column, 'oracle')))))
    return { type: oracledb.DB_TYPE_VARCHAR, maxSize }
  }
  const toBind = (value, column) => {
    const prepared = prepareValue(value, column, 'oracle')
    if (prepared === null) return null
    // Les entiers 32 bits et flottants passent en nombre ; décimaux et grands entiers restent en texte exact.
    if (NUMBER_TYPES.includes(column.type)) return Number(prepared)
    if (column.type === 'binary') return prepared
    return String(prepared)
  }
  const placeholder = (column, index) => {
    if (['date', 'timestamp'].includes(column.type)) return `TO_TIMESTAMP(:${index}, 'YYYY-MM-DD HH24:MI:SS.FF')`
    if (column.type === 'timestamptz') return `TO_TIMESTAMP_TZ(:${index}, 'YYYY-MM-DD HH24:MI:SS.FF TZH:TZM')`
    return `:${index}`
  }
  const adapter = {
    kind: 'oracle',
    transactional: false,
    quote: q,
    table: q,
    ph: (index) => `:${index + 1}`,
    page: offsetFetch,
    selectList: (columns) => columns.map((column) => oracleSelectExpression(column, q)).join(', '),
    query: async (sql, params = []) => (await connection.execute(sql, params, { autoCommit: true })).rows || [],
    listTables: async () => (await adapter.query('SELECT table_name AS "name" FROM all_tables WHERE owner = :1 AND nested = \'NO\' AND secondary = \'N\' ORDER BY table_name', [owner])).map((row) => row.name),
    getColumns: async (table) => canonicalColumns((await adapter.query(
      `SELECT c.column_name AS "name", c.data_type AS "rawType", c.char_length AS "length", c.data_precision AS "precision", c.data_scale AS "scale",
              CASE WHEN c.nullable = 'Y' THEN 1 ELSE 0 END AS "nullable", c.data_default AS "defaultValue",
              CASE WHEN c.identity_column = 'YES' THEN 1 ELSE 0 END AS "identity",
              CASE WHEN EXISTS (SELECT 1 FROM all_constraints uc JOIN all_cons_columns ucc ON ucc.owner = uc.owner AND ucc.constraint_name = uc.constraint_name
                                WHERE uc.owner = c.owner AND uc.constraint_type = 'P' AND uc.table_name = c.table_name AND ucc.column_name = c.column_name)
                   THEN 1 ELSE 0 END AS "primary"
       FROM all_tab_columns c WHERE c.owner = :1 AND c.table_name = :2 ORDER BY c.column_id`, [owner, table],
    )).map((row) => ({
      ...row, length: Number(row.length) || null, precision: row.precision == null ? null : Number(row.precision),
      scale: row.scale == null ? null : Number(row.scale), nullable: row.nullable === '1', primary: row.primary === '1', identity: row.identity === '1',
    })), 'oracle'),
    getForeignKeys: async (table) => groupForeignKeys(await adapter.query(
      `SELECT c.constraint_name AS "name", cc.column_name AS "col", rc.table_name AS "refTable", rcc.column_name AS "refCol", c.delete_rule AS "onDelete"
       FROM all_constraints c
       JOIN all_cons_columns cc ON cc.owner = c.owner AND cc.constraint_name = c.constraint_name
       JOIN all_constraints rc ON rc.owner = c.r_owner AND rc.constraint_name = c.r_constraint_name
       JOIN all_cons_columns rcc ON rcc.owner = rc.owner AND rcc.constraint_name = rc.constraint_name AND rcc.position = cc.position
       WHERE c.owner = :1 AND c.constraint_type = 'R' AND c.table_name = :2 ORDER BY c.constraint_name, cc.position`, [owner, table],
    )),
    getIndexes: async (table) => groupIndexes((await adapter.query(
      `SELECT i.index_name AS "name", CASE WHEN i.uniqueness = 'UNIQUE' THEN 1 ELSE 0 END AS "unique", ic.column_name AS "col",
              CASE WHEN i.index_type = 'NORMAL' THEN 0 ELSE 1 END AS "complex"
       FROM all_indexes i JOIN all_ind_columns ic ON ic.index_owner = i.owner AND ic.index_name = i.index_name
       WHERE i.table_owner = :1 AND i.table_name = :2 AND i.index_type <> 'LOB'
         AND NOT EXISTS (SELECT 1 FROM all_constraints c WHERE c.owner = i.table_owner AND c.table_name = i.table_name AND c.constraint_type = 'P' AND c.index_name = i.index_name)
       ORDER BY i.index_name, ic.column_position`, [owner, table],
    )).map((row) => ({ ...row, unique: row.unique === '1', complex: row.complex === '1' }))),
    getChecks: async (table) => (await adapter.query(
      `SELECT constraint_name AS "name", search_condition_vc AS "cond" FROM all_constraints
       WHERE owner = :1 AND table_name = :2 AND constraint_type = 'C' AND generated = 'USER NAME' ORDER BY constraint_name`, [owner, table],
    )).map((row) => ({ name: row.name, clause: `CHECK (${row.cond})` })),
    dropTable: (table) => adapter.query(
      `BEGIN EXECUTE IMMEDIATE 'DROP TABLE ${q(table).replaceAll("'", "''")} CASCADE CONSTRAINTS'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -942 THEN RAISE; END IF; END;`,
    ),
    insertRows: async (table, columns, rows) => {
      const sql = `INSERT INTO ${q(table)} (${columns.map((column) => q(column.name)).join(', ')}) VALUES (${columns.map((column, index) => placeholder(column, index + 1)).join(', ')})`
      for (const batch of chunk(rows, 5000)) {
        await connection.executeMany(sql, batch.map((row) => columns.map((column) => toBind(row[column.name], column))), {
          autoCommit: true, bindDefs: columns.map((column) => bindDef(column, batch)),
        })
      }
    },
    // Reprend la numérotation après la plus grande valeur insérée.
    syncIdentity: (table, column) => adapter.query(`ALTER TABLE ${q(table)} MODIFY (${q(column)} GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE))`),
    close: () => connection.close(),
  }
  return adapter
}

async function open(kind, connectionString) {
  if (kind === 'sqlite') return connectSqlite(connectionString)
  const url = new URL(connectionString)
  if (kind === 'mysql') return connectMysql(url)
  if (kind === 'postgres') return connectPostgres(url)
  if (kind === 'mssql') return connectMssql(url)
  return connectOracle(url)
}

export function kindOf(connectionString) {
  const protocol = String(connectionString || '').match(/^([a-z0-9]+):/i)?.[1]?.toLowerCase()
  return PROTOCOLS[protocol] || null
}

export async function connect(connectionString) {
  const kind = kindOf(connectionString)
  if (!kind) throw new Error(`Protocole non pris en charge. Utilisez ${SUPPORTED_PROTOCOLS}.`)
  const adapter = await open(kind, connectionString)
  adapter.read ??= adapter.query
  adapter.count ??= async (table) => Number(Object.values((await adapter.query(`SELECT COUNT(*) AS n FROM ${adapter.table(table)}`))[0])[0])
  adapter.createTablePlan = (table, columns, foreignKeys) => buildCreateTable(adapter, table, columns, foreignKeys)
  adapter.foreignKeyStatement = (table, fk) => `ALTER TABLE ${adapter.table(table)} ADD ${foreignKeySql(adapter, table, fk)}`
  adapter.indexStatement = (table, index) => indexSql(adapter, table, index)
  adapter.checkStatement = (table, check) => `ALTER TABLE ${adapter.table(table)} ADD CONSTRAINT ${adapter.quote(String(check.name).slice(0, 60))} ${check.clause}`
  adapter.addForeignKey = (table, fk) => adapter.query(adapter.foreignKeyStatement(table, fk))
  adapter.createIndex = (table, index) => adapter.query(adapter.indexStatement(table, index))
  adapter.addCheck = (table, check) => adapter.query(adapter.checkStatement(table, check))

  // Lecture par lots ordonnés sur la clé primaire : la table n'est jamais chargée entière en mémoire.
  // Sans clé primaire, l'ordre ne serait pas stable d'un lot à l'autre : la table est lue d'un bloc.
  adapter.readBatches = async function* readBatches(table, columns, size = 5000) {
    const select = `SELECT ${adapter.selectList(columns)} FROM ${adapter.table(table)}`
    const primary = columns.filter((column) => column.primary)
    if (!primary.length) { yield await adapter.read(select); return }
    const order = `ORDER BY ${primary.map((column) => adapter.quote(column.name)).join(', ')}`
    for (let offset = 0; ; offset += size) {
      const rows = await adapter.read(`${select} ${adapter.page(order, size, offset)}`)
      if (rows.length) yield rows
      if (rows.length < size) return
    }
  }

  // Mise à jour : suppression des lignes de même clé avant réinsertion (portable sur tous les moteurs).
  adapter.deleteByKeys = async (table, keyColumns, rows) => {
    const perBatch = Math.max(1, Math.floor(900 / keyColumns.length))
    for (const batch of chunk(rows, perBatch)) {
      const values = []
      const conditions = batch.map((row) => `(${keyColumns.map((column) => {
        values.push(prepareValue(row[column.name], column, adapter.kind))
        return `${adapter.quote(column.name)} = ${adapter.ph(values.length - 1)}`
      }).join(' AND ')})`)
      await adapter.query(`DELETE FROM ${adapter.table(table)} WHERE ${conditions.join(' OR ')}`, values)
    }
  }
  return adapter
}

export async function withDatabase(connectionString, action) {
  const database = await connect(connectionString)
  try { return await action(database) } finally { await database.close() }
}

// Masque le mot de passe d'une chaîne de connexion pour l'affichage.
export function maskConnection(connectionString) {
  try {
    if (kindOf(connectionString) === 'sqlite') return connectionString
    const url = new URL(connectionString)
    if (url.password) url.password = '••••'
    return decodeURIComponent(url.toString())
  } catch { return '(chaîne illisible)' }
}
